"""Media asset sourcing, synthesis and validation for demo_showcase_seed (#848).

All parsing/synthesis here is stdlib-only (Python 3.9+) and fully offline:

- Source reuse: the 16 real JPGs under frontend/public/seed-media/real/covers
  (NOTE: seed-media/real/gallery holds SVG placeholders, covers/ holds the
  real JPGs) and the two real MP4s under .../videos/fitness-{1,2}.mp4.
  fitness-3.mp4 is a mislabelled JPEG (ffd8 magic, 3456x4608) and is
  deliberately NOT used as a video source.
- Synthesis: WAV audio (pure-Python PCM; ffmpeg MP3 path used only when an
  ffmpeg binary is detected), MIDI sheet music, binary STL, mod zip, OPC
  docx, csv, plain-text notes.

Generated bytes are written into the caller-provided work directory (never
into tracked repo paths) and validated on every dry-run:

  kind      assertion
  --------  -----------------------------------------------------------
  image     JPEG SOF parse yields positive width/height; ffd8 magic
  video     MP4 box walk yields mvhd duration <=180s and tkhd 16.16 w/h
  audio     header magic matches the claimed extension (mirrors the backend
            upload_families.go audioMagicSignatures table)
  mod       zipfile.testzip() clean; PK magic; application/zip payload
  stl       84 + 50*triangle_count == file size; tetra normals normalized
  mid       MThd header + exactly one MTrk + running end-of-track
  docx      OPC identity parts ([Content_Types].xml + word/document.xml),
            no vbaProject.bin (mirrors document_validation.go checks)
  csv       no NUL bytes, printable ratio >= 0.9 (mirrors CSV sanity gate)
  text      non-empty UTF-8
"""
