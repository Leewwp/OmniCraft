def synthesize_audio(dest_dir: str, stem: str, ffmpeg_bin: Optional[str]) -> Dict[str, Any]:
    """Audio asset: ffmpeg MP3 when available, pure-Python WAV otherwise.

    Both paths must stay valid: the returned extension decides which magic
    prefix the validator expects (mirrors the backend sniffer).
    """
    if ffmpeg_bin:
        mp3_path = os.path.join(dest_dir, stem + ".mp3")
        try:
            proc = subprocess.run(
                [
                    ffmpeg_bin, "-y", "-f", "lavfi", "-i",
                    "sine=frequency=440:duration=6",
                    "-f", "lavfi", "-i", "sine=frequency=554.37:duration=6",
                    "-filter_complex", "amix=inputs=2,afade=t=in:d=0.5,afade=t=out:st=5.5:d=0.5",
                    "-codec:a", "libmp3lame", "-b:a", "128k", mp3_path,
                ],
                capture_output=True,
                text=True,
            )
        except (OSError, subprocess.SubprocessError):
            proc = None  # missing/unlaunchable binary: fall through to WAV
        if (
            proc is not None and proc.returncode == 0
            and os.path.exists(mp3_path) and os.path.getsize(mp3_path) > 0
        ):
            return {
                "path": mp3_path,
                "name": os.path.basename(mp3_path),
                "mime_type": "audio/mpeg",
                "file_type": "audio",
                "extension": ".mp3",
                "size": os.path.getsize(mp3_path),
                "duration_sec": 6,
            }
        # fall through to the WAV path on any ffmpeg failure
    return generate_wav(os.path.join(dest_dir, stem + ".wav"))


# ------------------------------------------------------------ validation

def validate_asset(asset: Dict[str, Any]) -> List[str]:
    """Offline assertions mirroring the backend upload-family gates."""
    issues: List[str] = []
    path = asset["path"]
    kind = asset["file_type"]
    ext = asset.get("extension") or os.path.splitext(path)[1].lower()
    if not os.path.exists(path):
        return ["missing file: %s" % path]
    if os.path.getsize(path) != asset["size"]:
        issues.append("size mismatch: stat=%d recorded=%d" % (os.path.getsize(path), asset["size"]))
    with open(path, "rb") as fh:
        head = fh.read(4096)
    if kind == "image":
        if head[:2] != b"\xff\xd8":
            issues.append("image missing JPEG SOI magic")
        try:
            width, height = jpeg_dimensions(path)
            if width <= 0 or height <= 0:
                issues.append("non-positive JPEG dimensions")
        except ValueError as err:
            issues.append("JPEG parse failed: %s" % err)
    elif kind == "video":
        try:
            meta = mp4_metadata(path)
            if meta["duration_sec"] > 180:
                issues.append("video duration %ds exceeds 180s budget" % meta["duration_sec"])
            if meta["width"] <= 0 or meta["height"] <= 0:
                issues.append("non-positive video dimensions")
        except ValueError as err:
            issues.append("MP4 parse failed: %s" % err)
    elif kind == "audio":
        prefixes = AUDIO_MAGIC_BY_EXT.get(ext, [])
        if not prefixes or not any(head.startswith(p) for p in prefixes):
            issues.append("audio header magic does not match extension %s" % ext)
    elif kind == "mod":
        if head[:2] != b"PK":
            issues.append("mod zip missing PK magic")
        try:
            with zipfile.ZipFile(path) as zf:
                bad = zf.testzip()
                if bad is not None:
                    issues.append("mod zip corrupt entry: %s" % bad)
                if len(zf.namelist()) < 2:
                    issues.append("mod zip too thin for archive validation")
        except zipfile.BadZipFile as err:
            issues.append("mod zip unreadable: %s" % err)
    elif kind == "model3d" and ext == ".stl":
        size = os.path.getsize(path)
        if size < 84:
            issues.append("STL smaller than fixed header")
        else:
            with open(path, "rb") as fh:
                fh.seek(80)
                count = struct.unpack("<I", fh.read(4))[0]
            if 84 + 50 * count != size:
                issues.append("STL size %d inconsistent with %d facets" % (size, count))
    elif kind == "sheet_music" and ext in (".mid", ".midi"):
        if head[:4] != b"MThd":
            issues.append("MIDI missing MThd header")
        elif len(head) < 14:
            issues.append("MIDI header truncated")
        else:
            header_len = struct.unpack(">I", head[4:8])[0]
            tracks = struct.unpack(">H", head[10:12])[0]
            if header_len != 6 or tracks < 1:
                issues.append("MIDI header fields invalid")
    elif kind == "document" and ext == ".docx":
        try:
            with zipfile.ZipFile(path) as zf:
                names = zf.namelist()
                if "[Content_Types].xml" not in names:
                    issues.append("docx missing [Content_Types].xml")
                if "word/document.xml" not in names:
                    issues.append("docx missing word/document.xml")
                if any(n.rsplit("/", 1)[-1].lower() == "vbaproject.bin" for n in names):
                    issues.append("docx carries vbaProject.bin")
                types = zf.read("[Content_Types].xml").decode("utf-8", "replace").lower()
                for marker in ("macro", "vbaProject"):
                    if marker in types:
                        issues.append("docx content types declare macro content")
        except zipfile.BadZipFile as err:
            issues.append("docx unreadable: %s" % err)
    elif kind == "document" and ext == ".csv":
        if b"\x00" in head:
            issues.append("csv contains NUL byte in head")
        else:
            printable = sum(1 for b in head if b in (0x0A, 0x0D, 0x09) or b >= 0x20)
            if head and printable / len(head) < 0.9:
                issues.append("csv printable ratio below 0.9")
    elif kind == "text":
        try:
            with open(path, "r", encoding="utf-8") as fh:
                if not fh.read().strip():
                    issues.append("text note empty")
        except UnicodeDecodeError:
            issues.append("text note not valid UTF-8")
    return issues


# ------------------------------------------------------------ library build

def ensure_demo_assets(workdir: str, use_ffmpeg: bool = True) -> Dict[str, List[Dict[str, Any]]]:
    """Materialize + validate every asset the seeding matrix needs.

    Returns a library dict: image/video sources keep absolute repo paths (no
    copies), synthesized families land in <workdir>/assets/. Re-running is
    idempotent: existing valid files are reused byte-for-byte.
    """
    assets_dir = os.path.join(workdir, "assets")
    os.makedirs(assets_dir, exist_ok=True)
    ffmpeg_bin = detect_ffmpeg() if use_ffmpeg else None

    library: Dict[str, List[Dict[str, Any]]] = {"image": [], "video": [], "audio": [], "mod": [], "sheet_music": [], "model3d": [], "document": [], "text": []}

    # -- sourced images (real JPGs, reused in place) -------------------------
    cover_names = sorted(n for n in os.listdir(COVERS_DIR) if n.lower().endswith(".jpg"))
    if len(cover_names) < 9:
        raise RuntimeError("expected >=9 real cover JPGs under %s, found %d" % (COVERS_DIR, len(cover_names)))
    for name in cover_names:
        path = os.path.join(COVERS_DIR, name)
        width, height = jpeg_dimensions(path)
        library["image"].append({
            "path": path, "name": name, "mime_type": "image/jpeg", "file_type": "image",
            "extension": ".jpg", "size": os.path.getsize(path),
            "width": width, "height": height, "duration_sec": None,
        })

    # -- sourced videos (real MP4s, reused in place) -------------------------
    for name in VIDEO_SOURCES:
        path = os.path.join(VIDEOS_DIR, name)
        meta = mp4_metadata(path)
        library["video"].append({
            "path": path, "name": name, "mime_type": "video/mp4", "file_type": "video",
            "extension": ".mp4", "size": os.path.getsize(path), "duration_sec": meta["duration_sec"],
            "width": meta["width"], "height": meta["height"],
        })
    # 3-video special needs a third real MP4: reuse fitness-1 bytes under a
    # distinct upload name (fitness-3.mp4 on disk is a mislabelled JPEG).
